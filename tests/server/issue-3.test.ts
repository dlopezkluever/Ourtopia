test('verified Invite creates only pending access; audited approval grants membership atomically and retries are semantic', async () => {
  const { owner, applicant, community } = await membershipFixture('approval');
  const intent = randomUUID();
  const invite = await issueInvite(owner, community.id, applicant.email, intent);
  const retry = await issueInvite(owner, community.id, applicant.email, intent);
  assert.deepEqual(retry, invite);
  assert.ok(Math.abs(Date.parse(invite.expires_at) - Date.now() - 7 * 86400000) < 10000);
  assert.equal((await owner.client.rpc('issue_invite', { p_intent_id: intent, p_community_id: community.id, p_email: 'changed@example.test' })).error?.code, '23505');
  const redemptionIntent = randomUUID();
  const application = await applyInvite(applicant, invite.id, redemptionIntent);
  assert.deepEqual(await applyInvite(applicant, invite.id, redemptionIntent), application);
  assert.deepEqual((await applicant.client.from('communities').select('*').eq('id', community.id)).data, []);
  assert.equal((await applicant.client.rpc('require_current_membership', { p_community_id: community.id })).error?.code, '42501');
  const decisionIntent = randomUUID();
  const decision = await decideApplication(owner, application.id, 'approved', '', decisionIntent);
  assert.equal(decision.error, null);
  assert.equal(decision.data.status, 'approved');
  assert.deepEqual((await decideApplication(owner, application.id, 'approved', '', decisionIntent)).data, decision.data);
  assert.equal((await decideApplication(owner, application.id, 'rejected', 'Changed', decisionIntent)).error?.code, '23505');
  assert.equal((await decideApplication(owner, application.id)).error?.code, '55000');
  assert.equal((await applicant.client.rpc('require_current_membership', { p_community_id: community.id })).error, null);
  assert.deepEqual((await applicant.client.from('memberships').select('role,status').eq('community_id', community.id).eq('user_id', applicant.id)).data, [{ role: 'member', status: 'active' }]);
  const event = await owner.client.from('community_events').select('*').eq('id', decision.data.decision_event_id);
  assert.equal(event.data?.length, 1);
  assert.equal(event.data?.[0].kind, 'membership_approved');
  receipt('issue-3-approval', { invite, application, decision: decision.data, audit: event.data });
});

test('expired consumed foreign and unverified Invites fail at execution with Cron absent', async () => {
  const { owner, applicant, community } = await membershipFixture('deadline');
  const expired = await issueInvite(owner, community.id, applicant.email);
  assert.equal((await admin.from('invites').update({ expires_at: new Date(Date.now() - 1000).toISOString() }).eq('id', expired.id)).error, null);
  assert.equal((await applicant.client.rpc('redeem_invite', { p_intent_id: randomUUID(), p_invite_id: expired.id })).error?.code, '22023');
  assert.deepEqual((await applicant.client.from('invites').select('*').eq('id', expired.id)).data, []);
  const unverified = await actor({ verified: false });
  const locked = await issueInvite(owner, community.id, unverified.email);
  assert.equal((await unverified.client.rpc('redeem_invite', { p_intent_id: randomUUID(), p_invite_id: locked.id })).error?.code, '42501');
  assert.deepEqual((await unverified.client.from('invites').select('*').eq('id', locked.id)).data, []);
  const invite = await issueInvite(owner, community.id, applicant.email);
  assert.equal((await unverified.client.rpc('redeem_invite', { p_intent_id: randomUUID(), p_invite_id: invite.id })).error?.code, '42501');
  const foreign = await actor();
  assert.equal((await foreign.client.rpc('redeem_invite', { p_intent_id: randomUUID(), p_invite_id: invite.id })).error?.code, '42501');
  await applyInvite(applicant, invite.id);
  assert.equal((await applicant.client.rpc('redeem_invite', { p_intent_id: randomUUID(), p_invite_id: invite.id })).error?.code, '55000');
  receipt('issue-3-deadlines', { expired: '22023', unverified: '42501', foreign: '42501', consumed: '55000', expiredRlsRows: 0 });
});

test('rejection reason is required; terminal history survives a fresh Invite and removal never reopens a request', async () => {
  const { owner, applicant, community } = await membershipFixture('terminal');
  const invite = await issueInvite(owner, community.id, applicant.email);
  const application = await applyInvite(applicant, invite.id);
  assert.equal((await decideApplication(owner, application.id, 'rejected')).error?.code, '22023');
  assert.equal((await admin.from('memberships').select('status').eq('community_id', community.id).eq('user_id', applicant.id)).data?.[0].status, 'pending');
  const rejected = await decideApplication(owner, application.id, 'rejected', 'Please attend an introduction first.');
  assert.equal(rejected.error, null);
  const own = await applicant.client.from('membership_applications').select('status,reason').eq('id', application.id);
  assert.deepEqual(own.data, [{ status: 'rejected', reason: 'Please attend an introduction first.' }]);
  assert.equal((await decideApplication(owner, application.id)).error?.code, '55000');
  const fresh = await issueInvite(owner, community.id, applicant.email);
  const second = await applyInvite(applicant, fresh.id);
  assert.notEqual(second.id, application.id);
  assert.equal((await decideApplication(owner, second.id)).error, null);
  assert.equal((await admin.from('memberships').update({ status: 'removed' }).eq('community_id', community.id).eq('user_id', applicant.id)).error, null);
  assert.equal((await applicant.client.rpc('require_current_membership', { p_community_id: community.id })).error?.code, '42501');
  assert.equal((await decideApplication(owner, second.id)).error?.code, '55000');
  const third = await applyInvite(applicant, (await issueInvite(owner, community.id, applicant.email)).id);
  assert.equal(third.status, 'pending');
  assert.equal((await applicant.client.from('membership_applications').select('id').eq('community_id', community.id)).data?.length, 3);
  receipt('issue-3-terminal', { rejected: rejected.data, freshApplication: second.id, afterRemovalApplication: third.id });
});

test('concurrent redemption and opposing decisions persist exactly one transition and coherent notice identities', async () => {
  const { owner, applicant, community } = await membershipFixture('race');
  const invite = await issueInvite(owner, community.id, applicant.email);
  const redemptions = await Promise.all(Array.from({ length: 4 }, () => applicant.client.rpc('redeem_invite', { p_intent_id: randomUUID(), p_invite_id: invite.id })));
  assert.equal(redemptions.filter(result => !result.error).length, 1);
  assert.deepEqual(redemptions.filter(result => result.error).map(result => result.error?.code), ['55000', '55000', '55000']);
  const application = redemptions.find(result => !result.error)!.data;
  const decisions = await Promise.all([decideApplication(owner, application.id, 'approved'), decideApplication(owner, application.id, 'rejected', 'Not this time.')]);
  assert.equal(decisions.filter(result => !result.error).length, 1);
  assert.equal(decisions.find(result => result.error)?.error?.code, '55000');
  const terminal = decisions.find(result => !result.error)!.data;
  const member = await admin.from('memberships').select('status').eq('community_id', community.id).eq('user_id', applicant.id);
  assert.equal(member.data?.[0].status, terminal.status === 'approved' ? 'active' : 'rejected');
  const notices = await admin.from('notification_outbox').select('event_id,recipient_id,channel,kind').eq('application_id', application.id);
  assert.equal(notices.data?.length, 4);
  assert.equal(new Set(notices.data!.map(row => JSON.stringify(row))).size, 4);
  receipt('issue-3-races', { redemptionCodes: redemptions.map(result => result.error?.code ?? 'ok'), decisionCodes: decisions.map(result => result.error?.code ?? 'ok'), terminal, notices: notices.data });
});

test('post-commit delivery failure and retry preserve approved membership and one delivered email identity', async () => {
  const { owner, applicant, community } = await membershipFixture('delivery');
  const application = await applyInvite(applicant, (await issueInvite(owner, community.id, applicant.email)).id);
  const decision = await decideApplication(owner, application.id);
  assert.equal(decision.error, null);
  const rows = await admin.from('notification_outbox').select('*').eq('event_id', decision.data.decision_event_id);
  assert.equal(rows.data?.length, 2);
  const email = rows.data!.find(row => row.channel === 'email')!;
  const inApp = rows.data!.find(row => row.channel === 'in_app')!;
  const failed = await deliverOne(admin, async () => { throw new Error('Forced provider failure before sending.'); }, email.id) as { state: string; attempts: number };
  assert.deepEqual({ state: failed.state, attempts: failed.attempts }, { state: 'failed', attempts: 1 });
  assert.equal((await applicant.client.rpc('require_current_membership', { p_community_id: community.id })).error, null);
  assert.equal((await owner.client.rpc('retry_notification', { p_intent_id: randomUUID(), p_outbox_id: email.id })).error, null);
  const { send } = localDelivery();
  const delivered = await deliverOne(admin, send, email.id) as { id: string; state: string; attempts: number };
  assert.deepEqual({ id: delivered.id, state: delivered.state, attempts: delivered.attempts }, { id: email.id, state: 'delivered', attempts: 2 });
  assert.equal(await deliverOne(admin, send, email.id), null);
  await deliverOne(admin, send, inApp.id);
  assert.equal(await deliverOne(admin, send, inApp.id), null);
  assert.equal((await applicant.client.from('notifications').select('*').eq('outbox_id', inApp.id)).data?.length, 1);
  const mailbox = await fetch(`${process.env.TEST_MAILBOX_URL}/api/v1/search?query=${encodeURIComponent(`to:${applicant.email}`)}`);
  const messages = await mailbox.json() as { messages: unknown[] };
  assert.equal(messages.messages.length, 1);
  const attempts = await owner.client.from('notification_attempts').select('number,error').eq('outbox_id', email.id).order('number');
  assert.deepEqual(attempts.data, [{ number: 1, error: 'Email delivery failed. Retry is scheduled.' }, { number: 2, error: null }]);
  receipt('issue-3-delivery', { membershipApproved: true, outboxId: email.id, delivered, attempts: attempts.data, mailboxMessages: messages.messages.length });
});

test('delivery claims serialize and expired worker leases cannot finish a newer attempt', async () => {
  const { owner, applicant, community } = await membershipFixture('lease');
  const application = await applyInvite(applicant, (await issueInvite(owner, community.id, applicant.email)).id);
  const decision = await decideApplication(owner, application.id);
  assert.equal(decision.error, null);
  const notice = await admin.from('notification_outbox').select('id').eq('event_id', decision.data.decision_event_id).eq('channel', 'in_app').single();
  const claims = await Promise.all([0, 1].map(() => admin.rpc('claim_notification', { p_outbox_id: notice.data!.id })));
  for (const claim of claims) assert.equal(claim.error, null);
  assert.equal(claims.filter(claim => claim.data !== null).length, 1);
  const first = claims.find(claim => claim.data !== null)!.data;
  assert.equal((await admin.from('notification_outbox').update({ lease_until: new Date(Date.now() - 1000).toISOString() }).eq('id', notice.data!.id)).error, null);
  const reclaimed = await admin.rpc('claim_notification', { p_outbox_id: notice.data!.id });
  assert.equal(reclaimed.error, null);
  assert.notEqual(reclaimed.data.claim_token, first.claim_token);
  assert.equal(reclaimed.data.attempts, 2);
  assert.equal((await admin.rpc('finish_notification', { p_outbox_id: notice.data!.id, p_claim_token: first.claim_token })).error?.code, '55000');
  assert.equal((await admin.rpc('finish_notification', { p_outbox_id: notice.data!.id, p_claim_token: reclaimed.data.claim_token })).data.state, 'delivered');
  assert.equal((await applicant.client.from('notifications').select('id').eq('outbox_id', notice.data!.id)).data?.length, 1);
  receipt('issue-3-delivery-leases', { outboxId: notice.data!.id, concurrentClaims: 1, attempts: 2, staleFinish: '55000', deliveredNotices: 1 });
});
